const BOX = ['11111', '10001', '10001', '10001', '10001', '10001', '11111'];

export const GLYPH_W = 6;
export const GLYPH_H = 8;

/** Width in pixels of `text` at integer `scale`. */
export function textWidth(text: string, scale: number): number {
  return text.length * GLYPH_W * scale;
}

/**
 * Stamp `text` into a straight RGBA8 image at (x, y) (top-left), `scale` pixels per font pixel, with a
 * 1-pixel dark outline so labels read on any background.
 */
export function drawText(img: Uint8Array, w: number, h: number, x: number, y: number, text: string, rgb: readonly [number, number, number], scale = 2): void {
  const put = (px: number, py: number, c: readonly [number, number, number], a: number): void => {
    if (px < 0 || py < 0 || px >= w || py >= h) return;
    const o = (py * w + px) * 4;
    const k = a / 255;
    const ba = (img[o + 3] as number) / 255;
    const oa = k + ba * (1 - k);
    for (let i = 0; i < 3; i++) img[o + i] = Math.round(oa > 0 ? ((c[i] as number) * k + (img[o + i] as number) * ba * (1 - k)) / oa : 0);
    img[o + 3] = Math.round(oa * 255);
  };
  for (let pass = 0; pass < 2; pass++) {
    let cx = x;
    for (const ch of text) {
      const g = GLYPHS[ch.toUpperCase()] ?? BOX;
      for (let r = 0; r < 7; r++) {
        const row = g[r] as string;
        for (let c = 0; c < 5; c++) {
          if (row[c] !== '1') continue;
          for (let sy = 0; sy < scale; sy++) {
            for (let sx = 0; sx < scale; sx++) {
              const px = cx + c * scale + sx;
              const py = y + r * scale + sy;
              if (pass === 0) {
                for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) put(px + dx, py + dy, [4, 8, 16], 200);
              } else {
                put(px, py, rgb, 255);
              }
            }
          }
        }
      }
      cx += GLYPH_W * scale;
    }
  }
}
